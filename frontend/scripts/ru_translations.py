s = open(p, encoding="utf-8").read()
missing = set()
def fix(m):
    src = html.unescape(m.group(1))
    if src in RU:
        return m.group(0)[:m.start(2)-m.start(0)] + html.escape(RU[src], quote=False) + m.group(0)[m.end(2)-m.start(0):]
    missing.add(src); return m.group(0)
